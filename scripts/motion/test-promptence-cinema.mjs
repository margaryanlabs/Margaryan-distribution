#!/usr/bin/env node
/** Fast, offline safety tests. Real WebGL rendering is a separate workstation test. */
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { resolve } from "node:path";
const root=resolve(process.cwd());
const r=(p)=>readFileSync(resolve(root,p),"utf8");
const script="scripts/motion/render-promptence-cinema.mjs";
const f=r("lib/motion/cinema/promptence-film.ts");
const p=r("app/motion/cinema/page.tsx");
const cli=r(script);
const run=(args)=>spawnSync(process.execPath,[script,...args],{cwd:root,encoding:"utf8",timeout:8000});
let x=run(["out/cinema.mp4","--dry-run","--concept","--fps","30"]);
assert.equal(x.status,0,x.stderr);
const plan=JSON.parse(x.stdout);
assert.equal(plan.duration,10);
assert.equal(plan.dimensions,"1920x1080");
assert.equal(plan.authenticProductSource,false);
assert.equal(plan.demoOnly,true);
x=run(["out/cinema.mp4","--dry-run"]);
assert.notEqual(x.status,0,"Product screenshot must be required by default");
assert.match(x.stderr,/screenshot is required/);
x=run(["out/cinema.mp4","--concept","--dry-run","--fps","12"]);
assert.notEqual(x.status,0,"Unsupported frame rates must fail");
x=run(["out/cinema.mp4","--concept","--dry-run","--url","https://evil.invalid/motion/cinema"]);
assert.notEqual(x.status,0,"Remote render sources must fail");
assert.match(f,/new THREE\.WebGLRenderer/);
assert.match(f,/new THREE\.PerspectiveCamera/);
assert.match(f,/new THREE\.MeshPhysicalMaterial/);
assert.match(f,/new THREE\.CatmullRomCurve3/);
assert.match(f,/screen\.visible = true/);
assert.match(f,/NOT LIVE RESULTS OR A PRODUCT SCREENSHOT/);
assert.match(f,/createReflectionStudio/);
assert.match(f,/THREE\.PMREMGenerator/);
assert.match(f,/file\.size > 12_000_000/);
assert.match(f,/renderer\.render\(world, camera\)/);
assert.match(p,/\/motion\/brands\/promptence\.svg/);
assert.match(p,/__motionCinemaSeek/);
assert.match(p,/data-testid="cinema-source"/);
assert.match(cli,/ffprobe/);
assert.match(cli,/WebGL unavailable/);
assert.ok(!/^\\s*(?:import|require)\\b[^\\n]*(?:espeak|pillow)/im.test(f));
assert.match(r("app/motion/page.tsx"),/href="\/motion\/cinema"/);
const syntax=spawnSync(process.execPath,["--check",script],{encoding:"utf8"});
assert.equal(syntax.status,0,syntax.stderr);
console.log("Promptence WebGL Cinema — safety, source integrity, native frame and CLI contracts PASS");
