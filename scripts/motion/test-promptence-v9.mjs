#!/usr/bin/env node
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {spawnSync} from "node:child_process";
const film=readFileSync("lib/motion/cinema/promptence-film-v9.ts","utf8");
const page=readFileSync("app/motion/cinema/v9/page.tsx","utf8");
const renderer=readFileSync("scripts/motion/render-promptence-v9.mjs","utf8");
const cmd=arg=>spawnSync(process.execPath,["scripts/motion/render-promptence-v9.mjs","out/v9.mp4",...arg],{encoding:"utf8",timeout:10000});
const r=cmd(["--dry-run","--concept","--fps","24"]);
assert.equal(r.status,0,r.stderr);
const config=JSON.parse(r.stdout);
assert.equal(config.duration,8);
assert.equal(config.fps,24);
assert.equal(config.dimensions,"1920x1080");
assert.equal(config.demoOnly,true);
const publicRun=cmd(["--dry-run","--capture-public"]);
assert.equal(publicRun.status,0,publicRun.stderr);
assert.equal(JSON.parse(publicRun.stdout).authenticProductSource,true);
assert.match(film,/new THREE\.WebGLRenderer/);
assert.match(film,/new THREE\.PerspectiveCamera/);
assert.match(film,/new THREE\.MeshPhysicalMaterial/);
assert.match(film,/CylinderGeometry/);
assert.match(film,/new THREE\.EllipseCurve/);
assert.match(film,/keyboardMat/);
assert.match(film,/PROMPTENCE/);
assert.match(film,/setScreen\(file:File\)/);
assert.match(page,/createV9Film/);
assert.match(page,/zIndex:2147483647/);
assert.match(page,/data-testid="cinema-source"/);
assert.match(renderer,/\[.6, 2.65, 5.25, 7.4\]/);
assert.match(renderer,/Cinema stage is not isolated/);
const syntax=spawnSync(process.execPath,["--check","scripts/motion/render-promptence-v9.mjs"],{encoding:"utf8"});
assert.equal(syntax.status,0,syntax.stderr);
console.log("V9 8s real 3D cinema and source/QA contracts PASS");
