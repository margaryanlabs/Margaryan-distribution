#!/usr/bin/env node
/**
 * Markarian Edge V1: renders a reviewable HAProxy staging configuration.
 * Pure source transformation. No network, Docker, Coolify or DNS writes.
 *
 * Routing uses private RFC1918 IPv4 origins only and health checks all backends.
 * Operator-supplied zones/SHA are DECLARATIONS, not measured attestations.
 */
import {readFileSync,lstatSync} from 'node:fs';
import {isAbsolute} from 'node:path';
import {pathToFileURL} from 'node:url';

const NAME=/^[a-z][a-z0-9-]{0,47}$/;
const ZONE=/^[a-z][a-z0-9-]{0,63}$/;
const SHA=/^[a-f0-9]{40}$/;
const KNOWN=['vetogram','promptence'];
const KEYS=['schema','environment','tlsTermination','publishHostPorts','services'];
const SVC=['id','listenPort','healthPath','expectedSourceSha','backends'];
const BACKEND=['id','ip','port','zone'];
function exact(obj,keys){
 return obj!==null&&typeof obj==='object'&&!Array.isArray(obj)&&
  Object.keys(obj).length===keys.length&&Object.keys(obj).every(k=>keys.includes(k));
}
function reject(reason){throw Error(reason);}
export function isPrivateIpv4(value){
 if(typeof value!=='string'||!/^(?:0|[1-9][0-9]{0,2})(?:\.(?:0|[1-9][0-9]{0,2})){3}$/.test(value))return false;
 const parts=value.split('.').map(Number);
 if(parts.some(n=>n>255))return false;
 // Reject likely network/broadcast targets and metadata/link-local/loopback.
 if(parts[3]===0||parts[3]===255)return false;
 return parts[0]===10||(parts[0]===172&&parts[1]>=16&&parts[1]<=31)||
  (parts[0]===192&&parts[1]===168);
}
export function validateEdgeConfig(input){
 if(!exact(input,KEYS)||input.schema!=='markarian-edge/v1'||
  input.environment!=='staging'||input.tlsTermination!=='external'||
  input.publishHostPorts!==false||!Array.isArray(input.services)||
  input.services.length!==2)reject('Invalid staging edge manifest');
 const ids=new Set(),ports=new Set(),usedTargets=new Set();
 for(const svc of input.services){
  if(!exact(svc,SVC)||!KNOWN.includes(svc.id)||ids.has(svc.id)||
   !Number.isInteger(svc.listenPort)||svc.listenPort<1024||svc.listenPort>65535||
   ports.has(svc.listenPort)||!['/healthz','/api/health'].includes(svc.healthPath)||
   !SHA.test(svc.expectedSourceSha)||!Array.isArray(svc.backends)||
   svc.backends.length<2||svc.backends.length>64)reject('Invalid edge service');
  ids.add(svc.id);ports.add(svc.listenPort);
  const hosts=new Set(),zones=new Set(),serverIds=new Set();
  for(const host of svc.backends){
   if(!exact(host,BACKEND)||!NAME.test(host.id)||!ZONE.test(host.zone)||
    !isPrivateIpv4(host.ip)||!Number.isInteger(host.port)||host.port<1||
    host.port>65535||hosts.has(host.ip+':'+host.port)||serverIds.has(host.id))
    reject('Invalid, duplicate, or public edge origin');
   hosts.add(host.ip+':'+host.port);serverIds.add(host.id);zones.add(host.zone);
   // Service instances must not reuse one private IP:port across products.
   if(usedTargets.has(host.ip+':'+host.port))reject('Cross-product edge origin collision');
   usedTargets.add(host.ip+':'+host.port);
  }
  if(zones.size<2)reject('At least two declared zones required per staging service');
 }
 if(ids.size!==2)reject('Both VETOGRAM and Promptence must be declared');
 return input;
}
function label(id){return id.replaceAll('-','_');}
export function renderHaproxy(input){
 const cfg=validateEdgeConfig(input);
 const lines=[
  '# Generated by Markarian Cloud, staging only. Never edit a live proxy without review.',
  '# Backend zones and expected source SHA are operator declarations, NOT verified here.',
  'global',
  '  log stdout format raw local0',
  '  maxconn 2048',
  'defaults',
  '  log global',
  '  mode http',
  '  option httplog',
  '  option dontlognull',
  '  option forwardfor',
  '  timeout connect 5s',
  '  timeout client 45s',
  '  timeout server 45s',
  '  timeout tunnel 1h',
  ''
 ];
 for(const svc of [...cfg.services].sort((a,b)=>a.id.localeCompare(b.id))){
  const id=label(svc.id);
  lines.push('frontend fe_'+id);
  lines.push('  bind :'+svc.listenPort);
  lines.push('  default_backend be_'+id);
  lines.push('');
  lines.push('backend be_'+id);
  lines.push('  balance leastconn');
  lines.push('  option httpchk GET '+svc.healthPath);
  lines.push('  http-check expect status 200');
  lines.push('  default-server inter 3s fall 3 rise 2');
  for(const host of [...svc.backends].sort((a,b)=>a.id.localeCompare(b.id))){
   lines.push('  server '+label(host.id)+' '+host.ip+':'+host.port+' check');
  }
  lines.push('');
 }
 return lines.join('\n')+'\n';
}
export function edgePlan(input){
 const cfg=validateEdgeConfig(input);
 return {schema:'markarian-edge-plan/v1',environment:'staging',
  listeners:cfg.services.map(s=>({service:s.id,port:s.listenPort,origins:s.backends.length})),
  routing:'PRIVATE_HTTP_BEHIND_EXTERNAL_TLS',
  zoneLabelsIndependentlyVerified:false,actualOriginHealthVerified:false,
  imageDigestsVerified:false,databaseHaVerified:false,edgeHaVerified:false,
  canPublishPublicPort:false,canDeploy:false,canChangeDNS:false,
  note:'A syntactically valid HAProxy config does not prove live routing or load balancer HA.'};
}
function loadFile(file){
 if(typeof file!=='string'||!isAbsolute(file))reject('Absolute manifest path required');
 const st=lstatSync(file);
 if(!st.isFile()||st.isSymbolicLink()||st.size>262144)reject('Unsafe edge manifest');
 return validateEdgeConfig(JSON.parse(readFileSync(file,'utf8')));
}
export function main(argv=process.argv.slice(2)){
 if(argv.length!==2||!['--plan','--render'].includes(argv[0])){
  process.stderr.write('Usage: edge-render.mjs --plan|--render /absolute/staging-edge.json\n');
  return 2;
 }
 try{
  const config=loadFile(argv[1]);
  if(argv[0]==='--plan')process.stdout.write(JSON.stringify(edgePlan(config),null,2)+'\n');
  else process.stdout.write(renderHaproxy(config));
  return 0;
 }catch{
  process.stderr.write('EDGE NOT READY: invalid/unsafe manifest; no configuration emitted.\n');
  return 1;
 }
}
if(process.argv[1]&&pathToFileURL(process.argv[1]).href===import.meta.url)process.exitCode=main();
